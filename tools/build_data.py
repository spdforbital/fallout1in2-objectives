#!/usr/bin/env python3
"""Build the Objectives data: validates data/steps/*.txt and writes

  build/objectives_data.h    SSL include compiled into gl_objectives.int
  build/objectives_data.json the same data as JSON (for tests / inspection)

Exit code 1 on validation errors.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import objdata as od  # noqa: E402

OUT = os.path.join(od.ROOT, "build")
# GVARs the SSL script uses directly (water / invasion timers)
EXTRA_GVARS = ["GVAR_VAULT_WATER", "GVAR_VAULT13_WATER_DAYS", "GVAR_VAULT13_WATER_DAYS_COUNTER",
               "GVAR_VAULT_13_INVASION_DAYS", "GVAR_VAULT_13_WAS_INVADED",
               "GVAR_MASTER_BLOWN_CUTSCENE", "GVAR_VATS_BLOWN_CUTSCENE_DONE"]
CONST = {}


def ssl_str(s):
    s = s.replace("\\", "/").replace('"', "'")
    return '"' + s + '"'


def palette_index(rgb, avoid0=True):
    """Closest colour in the game palette (color.pal, 6-bit RGB)."""
    with open(os.path.join(od.BASE, "color.pal"), "rb") as f:
        pal = f.read(768)
    best, bi = None, 1
    for i in range(1 if avoid0 else 0, 229):  # 229+ are animated colours
        r, g, b = pal[i * 3] * 4, pal[i * 3 + 1] * 4, pal[i * 3 + 2] * 4
        d = (r - rgb[0]) ** 2 + (g - rgb[1]) ** 2 + (b - rgb[2]) ** 2
        if best is None or d < best:
            best, bi = d, i
    return bi


def flatten(model, ctx):
    """Turn the model into flat tables + int pools (the layout the SSL script uses)."""
    cpool = []   # conditions: [n_atoms, atoms*5...]
    ipool = []   # where / targets / count lists

    def cond(atoms):
        off = len(cpool)
        cpool.append(len(atoms))
        for a in atoms:
            cpool.extend(a)
        return off

    def ilist(vals):
        off = len(ipool)
        ipool.extend(vals)
        return off, len(vals)

    town_idx = {t: i for i, (t, _) in enumerate(od.TOWNS)}
    qidx = {q["id"]: i for i, q in enumerate(model)}
    Q, S = [], []
    for q in model:
        s0 = len(S)
        for s in q["steps"]:
            w0, wn = ilist([m * 8 + (e + 1) for m, e in s["where"]])
            t0, tn = ilist(s["targets"])
            k0, kn = ilist(s["count"])
            label = ""
            if s["where_names"]:
                label = od.MAP_INFO.get(s["where_names"][0], (q["town"], s["where_names"][0]))[1]
            S.append(dict(text=s["text"], note=s["note"], label=label, w0=w0, wn=wn,
                          tkind=s["tkind"], t0=t0, tn=tn, k0=k0, kn=kn,
                          done=cond(s["done"]), show=cond(s["show"]), alt=s["alt"]))
        Q.append(dict(key=q["key"], id=q["id"], name=q["name"], town=town_idx[q["town"]],
                      main=1 if q["kind"] == "main" else 0, pipboy=q["pipboy"],
                      comp=1 if q["kind"] == "companion" else 0, rep=q["repeatable"],
                      # cut content: can never be started -> hidden from the quest tree
                      cut=1 if q["active"] == [[od.C_FALSE, 0, 0, 0, 0]] and
                      q["unlock"] == [[od.C_FALSE, 0, 0, 0, 0]] else 0,
                      desc=q.get("desc", ""), active=cond(q["active"]),
                      done=cond(q["done"]), fail=cond(q["fail"]), s0=s0,
                      unlock=cond(q["unlock"]), parent=qidx.get(q["parent"], -1),
                      giver=q["giver"], lockhint=q["lockhint"],
                      sn=len(S) - s0))
    maps_town = {}
    maps_label = {}
    for name, (town, label) in od.MAP_INFO.items():
        num = ctx.const["MAP"].get("MAP_" + name)
        if num is not None:
            maps_town[num] = town_idx[town]
            maps_label[num] = label
    towns = []
    for t, area in od.TOWNS:
        x, y = ctx.areas.get(area, (0, 0))
        towns.append(dict(name=t, area=area, x=x, y=y))
    return dict(quests=Q, steps=S, cpool=cpool, ipool=ipool, towns=towns,
                maps_town=maps_town, maps_label=maps_label)


def emit_ssl(flat, path):
    Q, S = flat["quests"], flat["steps"]
    L = []
    w = L.append
    w("/* GENERATED by tools/build_data.py from data/steps (one file per town) -- do not edit */")
    w("#define OBJ_NQ (%d)" % len(Q))
    w("#define OBJ_NS (%d)" % len(S))
    w("#define OBJ_NTOWN (%d)" % len(flat["towns"]))
    w("#define OBJ_NMAPS (%d)" % (max(flat["maps_town"]) + 1))
    w("#define OBJ_COL_BG (%d)" % palette_index((10, 22, 10)))
    w("#define OBJ_COL_BORDER (%d)" % palette_index((40, 110, 40)))
    w("#define OBJ_COL_SEL (%d)" % palette_index((30, 70, 30)))
    for g in EXTRA_GVARS:
        w("#define %s (%d)" % (g, CONST["GVAR"][g]))
    w("")
    arrays = {
        "q_key": [q["key"] for q in Q], "q_name": [ssl_str(q["name"]) for q in Q],
        "q_town": [q["town"] for q in Q], "q_main": [q["main"] for q in Q],
        "q_desc": [ssl_str(q["desc"]) for q in Q], "q_active": [q["active"] for q in Q],
        "q_done": [q["done"] for q in Q], "q_fail": [q["fail"] for q in Q],
        "q_s0": [q["s0"] for q in Q], "q_sn": [q["sn"] for q in Q],
        "q_rep": [q["rep"] for q in Q], "s_q": [i for i, q in enumerate(Q) for _ in range(q["sn"])],
        "q_comp": [q["comp"] for q in Q], "q_cut": [q["cut"] for q in Q], "s_alt": [s["alt"] for s in S],
        "q_unlock": [q["unlock"] for q in Q], "q_parent": [q["parent"] for q in Q],
        "q_giver": [ssl_str(q["giver"]) for q in Q], "q_lockhint": [ssl_str(q["lockhint"]) for q in Q],
        "s_text": [ssl_str(s["text"]) for s in S], "s_note": [ssl_str(s["note"]) for s in S],
        "s_label": [ssl_str(s["label"]) for s in S],
        "s_w0": [s["w0"] for s in S], "s_wn": [s["wn"] for s in S],
        "s_tkind": [s["tkind"] for s in S], "s_t0": [s["t0"] for s in S],
        "s_tn": [s["tn"] for s in S], "s_k0": [s["k0"] for s in S],
        "s_kn": [s["kn"] for s in S], "s_done": [s["done"] for s in S],
        "s_show": [s["show"] for s in S],
        "c_pool": flat["cpool"], "i_pool": flat["ipool"] or [0],
        "town_name": [ssl_str(t["name"]) for t in flat["towns"]],
        "town_x": [t["x"] for t in flat["towns"]], "town_y": [t["y"] for t in flat["towns"]],
    }
    nmaps = max(flat["maps_town"]) + 1
    arrays["map_town"] = [flat["maps_town"].get(i, -1) for i in range(nmaps)]
    arrays["map_label"] = [ssl_str(flat["maps_label"].get(i, "")) for i in range(nmaps)]
    w("variable " + ", ".join(arrays) + ";")
    w("")
    w("procedure ObjData_Load begin")
    for name, vals in arrays.items():
        w("   %s := create_array(%d, 0);" % (name, len(vals)))
        for i, v in enumerate(vals):
            if v not in (0, '""'):
                w("   %s[%d] := %s;" % (name, i, v))
    w("end")
    with open(path, "w", newline="\r\n") as f:
        f.write("\n".join(L) + "\n")


def main():
    ctx, model = od.build()
    for x in ctx.warnings:
        print("warning:", x)
    for e in ctx.errors:
        print("ERROR:", e)
    if ctx.errors:
        print("%d errors - nothing written" % len(ctx.errors))
        return 1
    CONST.update(ctx.const)
    for g in EXTRA_GVARS:
        if g not in ctx.const["GVAR"]:
            print("ERROR: script GVAR %s missing from global.h" % g)
            return 1
        ctx.check_gvar(ctx.const["GVAR"][g], "script", g)
    if ctx.errors:
        print("\n".join(ctx.errors))
        return 1
    os.makedirs(OUT, exist_ok=True)
    flat = flatten(model, ctx)
    emit_ssl(flat, os.path.join(OUT, "objectives_data.h"))
    with open(os.path.join(OUT, "objectives_data.json"), "w") as f:
        json.dump(dict(model=model, flat=flat), f, indent=1, default=str)
    print("wrote build/objectives_data.h and .json: %d quests, %d steps, %d pool ints" % (
        len(flat["quests"]), len(flat["steps"]), len(flat["cpool"]) + len(flat["ipool"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
